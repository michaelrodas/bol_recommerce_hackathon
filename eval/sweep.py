"""Threshold + top-k sweep for the retrieval eval.

Retrieves once per case at the max k, then scores every (k, threshold) combo to
find the config that best separates covered from not-covered cases. Writes the
winner to best-vdb-config.yml (consumed by apply_config.py).

Objective (default): maximise recall over covered cases, subject to rejecting at
least REJECT_TARGET of the negatives. A negative is "rejected" when no retrieved
chunk within top-k scores >= threshold, so retrieval returns empty -> escalation.
If no combo meets the target (scores overlap), fall back to maximising a balanced
score (recall + reject_rate) / 2. Ties break toward smaller k, then higher
threshold (safer).

Run:
    docker compose --profile eval run --rm eval python sweep.py
"""
import os
from datetime import datetime, timezone

import yaml

import harness  # reuse load_cases, retrieve, adjusted_page, PAGE_OFFSET

K_GRID = [int(x) for x in os.environ.get("K_GRID", "1,2,3,4,5").split(",")]
T_START = float(os.environ.get("T_START", "0.40"))
T_STOP = float(os.environ.get("T_STOP", "0.80"))
T_STEP = float(os.environ.get("T_STEP", "0.01"))
REJECT_TARGET = float(os.environ.get("REJECT_TARGET", "1.0"))
OUT = os.environ.get("BEST_CONFIG", "best-vdb-config.yml")


def thresholds() -> list[float]:
    n = int(round((T_STOP - T_START) / T_STEP)) + 1
    return [round(T_START + i * T_STEP, 4) for i in range(n)]


def covered_hit(case: dict, results: list, k: int, t: float) -> bool:
    """A covered case hits if some surviving top-k chunk is on an expected page."""
    expected = set(case["expected_pages"])
    kw = case.get("expected_keyword")
    for res in results[:k]:
        if res["score"] is None or res["score"] < t:
            continue
        page_ok = harness.adjusted_page(res) in expected
        kw_ok = kw is None or kw.lower() in (res.get("text") or "").lower()
        if page_ok and kw_ok:
            return True
    return False


def negative_rejected(results: list, k: int, t: float) -> bool:
    """A negative is rejected when nothing in top-k survives the threshold."""
    return all((r["score"] is None or r["score"] < t) for r in results[:k])


def main() -> None:
    cases = harness.load_cases()
    max_k = max(K_GRID)
    retrieved = {c["id"]: harness.retrieve(c["question"], topk=max_k) for c in cases}
    covered = [c for c in cases if c["category"] == "covered"]
    negatives = [c for c in cases if c["category"] != "covered"]

    best = None  # (rank_key, recall, reject_rate, k, t, meets)
    for k in K_GRID:
        for t in thresholds():
            hits = sum(covered_hit(c, retrieved[c["id"]], k, t) for c in covered)
            rej = sum(negative_rejected(retrieved[c["id"]], k, t) for c in negatives)
            recall = hits / len(covered) if covered else 0.0
            reject_rate = rej / len(negatives) if negatives else 1.0
            meets = reject_rate >= REJECT_TARGET
            primary = recall if meets else (recall + reject_rate) / 2
            # prefer meeting target, then primary; tie-break smaller k, higher threshold
            key = (meets, round(primary, 6), -k, t)
            if best is None or key > best[0]:
                best = (key, recall, reject_rate, k, t, meets)

    _, recall, reject_rate, k, t, meets = best
    if not meets:
        print(f"WARNING: no (k, threshold) rejected >= {REJECT_TARGET:.0%} of negatives "
              f"(scores overlap). Picked balanced best.")
    print(f"best: k={k} threshold={t}  recall={recall:.2f} reject_rate={reject_rate:.2f}")

    header = (
        f"# generated by sweep.py at {datetime.now(timezone.utc).isoformat(timespec='seconds')}\n"
        f"# objective: max recall s.t. reject_rate >= {REJECT_TARGET} "
        f"(fallback: balanced) | tie-break: smaller k, higher threshold\n"
        f"# achieved: recall={recall:.2f}, reject_rate={reject_rate:.2f}, target_met={meets}\n"
        f"# corpus: {len(covered)} covered + {len(negatives)} negative cases; "
        f"PAGE_OFFSET={harness.PAGE_OFFSET}\n"
    )
    with open(OUT, "w") as f:
        f.write(header)
        yaml.safe_dump({"best-k": k, "similarity-threshold": float(t)}, f, sort_keys=False)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
